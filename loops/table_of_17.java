package loops;
public class table_of_17 {

    public static void main(String[] args) {
        System.out.println("Write a Java program using a for loop to print the multiplication table of 17.");

        int n=17;
        for(int i=1;i<=10;i++){
System.out.println(n+"x"+i+"="+n*i);
        }
    }
}